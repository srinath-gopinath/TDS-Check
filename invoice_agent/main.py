# --- BUSINESS CRITERIA LOGIC ENGINE ---
def evaluate_business_action(pkg: InvoicePackage) -> tuple[str, list[str]]:
    evidence = []
    
    if pkg.proof_of_delivery:
        evidence.append("Verified physical or digital Proof of Delivery.")
    if pkg.authorization_on_file:
        evidence.append("Matched valid internal authorization documentation / PO.")
        
    if not pkg.proof_of_delivery or not pkg.authorization_on_file:
        missing = [k for k, v in {"proof_of_delivery": pkg.proof_of_delivery, "authorization_on_file": pkg.authorization_on_file}.items() if not v]
        return "HOLD_ESCALATE", [f"Missing required compliance records: {', '.join(missing)}."]

    if pkg.amount > pkg.delegated_limit:
        return "HOLD_ESCALATE", [f"Invoice amount (${pkg.amount}) exceeds authorized delegation limit (${pkg.delegated_limit})."]
        
    evidence.append(f"Invoice value (${pkg.amount}) sits inside allowed delegation limit (${pkg.delegated_limit}).")
    return "APPROVE_AND_PAY", evidence

# --- SECURE ENDPOINT ---
@app.post("/api/v1/invoice/process", response_model=ActionResponse, status_code=status.HTTP_200_OK)
async def process_invoice_package(pkg: InvoicePackage, db: AsyncSession = Depends(get_db)):
    result = await db.get(TaskState, pkg.idempotency_key)
    if result is not None:
        return ActionResponse(
            invoice_id=result.invoice_id,
            status=result.status,
            action_taken=result.action_taken,
            evidence_cited=result.evidence_log.split(" | ")
        )
    
    state_lock = TaskState(
        idempotency_key=pkg.idempotency_key,
        invoice_id=pkg.invoice_id,
        status="PENDING",
        action_taken="EVALUATING",
        evidence_log="Evaluating compliance data stream"
    )
    db.add(state_lock)
    await db.commit()
    
    action, evidence_list = evaluate_business_action(pkg)
    evidence_str = " | ".join(evidence_list)
    
    state_lock.status = "PAID" if action == "APPROVE_AND_PAY" else "HELD"
    state_lock.action_taken = action
    state_lock.evidence_log = evidence_str
    
    await db.merge(state_lock)
    await db.commit()
    await db.refresh(state_lock)
    
    if action == "APPROVE_AND_PAY":
        pass
    elif action == "HOLD_ESCALATE":
        pass

    return ActionResponse(
        invoice_id=pkg.invoice_id,
        status=state_lock.status,
        action_taken=action,
        evidence_cited=evidence_list
    )

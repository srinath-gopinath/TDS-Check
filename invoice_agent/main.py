import os
from typing import List, Optional
from pydantic import BaseModel, Field
from fastapi import FastAPI, HTTPException, status, Depends
from contextlib import asynccontextmanager
from sqlalchemy.ext.asyncio import create_async_engine, AsyncSession
from sqlalchemy.orm import declarative_base, sessionmaker
from sqlalchemy import Column, String, Float, Boolean, Text, DateTime
import datetime

# --- DATABASE SETUP & IDEMPOTENCY TRACKING ---
DATABASE_URL = os.getenv("DATABASE_URL", "sqlite+aiosqlite:///invoice_agent.db")
engine = create_async_engine(DATABASE_URL, echo=True)
async_session = sessionmaker(engine, class_=AsyncSession, expire_on_commit=False)
Base = declarative_base()

class TaskState(Base):
    __tablename__ = "task_states"
    idempotency_key = Column(String, primary_key=True, index=True)
    invoice_id = Column(String, nullable=False)
    status = Column(String, nullable=False)  # "PENDING", "APPROVED", "REJECTED", "PAID"
    action_taken = Column(String, nullable=False)
    evidence_log = Column(Text, nullable=False)
    updated_at = Column(DateTime, default=datetime.datetime.utcnow, onupdate=datetime.datetime.utcnow)

# --- MODERN LIFESPAN EVENT HANDLER ---
@asynccontextmanager
async def lifespan(app: FastAPI):
    # 1. Startup Logic: Executed once before the app starts receiving requests
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
    
    yield  # Handover to application request-handling loop
    
    # 2. Shutdown Logic: Executed once right before the app fully stops
    await engine.dispose()

# --- API MODELS ---
class InvoicePackage(BaseModel):
    idempotency_key: str = Field(..., description="Unique key generated by client to prevent duplicate runs")
    invoice_id: str
    amount: float
    vendor_id: str
    business_purpose: str
    proof_of_delivery: bool = Field(..., description="Evidence flag: verification of items received")
    authorization_on_file: bool = Field(..., description="Evidence flag: internal approval or PO map exists")
    delegated_limit: float = Field(..., description="The maximum amount authorized for this budget track holder")

class ActionResponse(BaseModel):
    invoice_id: str
    status: str
    action_taken: str
    evidence_cited: List[str]

# --- APP INITIALIZATION WITH LIFESPAN ---
app = FastAPI(title="HTTPS Secure Invoice Agent", version="1.0.0", lifespan=lifespan)

async def get_db():
    async with async_session() as session:
        yield session

